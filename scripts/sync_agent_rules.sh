#!/usr/bin/env bash
# Generate tool-specific agent rules from the canonical .agents/rules/ directory.
#
# .agents/rules/<name>.md is the source of truth (README.md there is not a rule).
# Each source has YAML frontmatter with `description` (required) and `paths`
# (optional list of globs relative to this repository; no paths = always on).
# This script generates:
#   - .claude/rules/<name>.md    Claude Code rules (`paths:` frontmatter)
#   - .cursor/rules/<name>.mdc   Cursor rules (`description`, `globs`, `alwaysApply`)
#   - the rule routing table in CLAUDE.md, between the agent-rules markers
#
# Generated rule files carry a "GENERATED" comment. Generated files whose source
# no longer exists are removed; files without the comment are never touched.
#
# Usage:
#   bash ./scripts/sync_agent_rules.sh           # regenerate everything
#   bash ./scripts/sync_agent_rules.sh --check   # report drift only; exit 1 if any

set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"

CHECK_ONLY=false
if [[ "${1:-}" == "--check" ]]; then
  CHECK_ONLY=true
elif [[ -n "${1:-}" ]]; then
  echo "Unknown option: $1 (expected --check or nothing)" >&2
  exit 2
fi

if [[ ! -d "$ROOT_DIR/.agents/rules" ]]; then
  echo "Source directory not found: $ROOT_DIR/.agents/rules" >&2
  exit 1
fi

if ! command -v python3 > /dev/null 2>&1; then
  echo "python3 is required but was not found on PATH." >&2
  exit 1
fi

python3 - "$ROOT_DIR" "$CHECK_ONLY" <<'PYTHON'
import re
import sys
from pathlib import Path

root = Path(sys.argv[1])
check_only = sys.argv[2] == "true"

source_dir = root / ".agents" / "rules"
claude_dir = root / ".claude" / "rules"
cursor_dir = root / ".cursor" / "rules"
claude_md = root / "CLAUDE.md"

MARKER_PREFIX = "<!-- GENERATED by scripts/sync_agent_rules.sh"
BEGIN_TABLE = "<!-- BEGIN GENERATED: agent-rules -->"
END_TABLE = "<!-- END GENERATED: agent-rules -->"
NAME_PATTERN = re.compile(r"^[a-z0-9]+(-[a-z0-9]+)*$")


def fail(message: str) -> None:
    print(message, file=sys.stderr)
    sys.exit(1)


def marker(name: str) -> str:
    return (
        f"{MARKER_PREFIX} from .agents/rules/{name}.md. "
        "Do not edit; edit the source and run the script. -->"
    )


def unquote(value: str) -> str:
    value = value.strip()
    if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
        return value[1:-1]
    return value


def parse_source(path: Path) -> dict:
    """Parse the restricted frontmatter format used by rule sources."""
    text = path.read_text(encoding="utf-8")
    lines = text.split("\n")
    if not lines or lines[0].strip() != "---":
        fail(f"{path.relative_to(root)}: missing frontmatter (first line must be '---')")
    try:
        end = lines.index("---", 1)
    except ValueError:
        fail(f"{path.relative_to(root)}: frontmatter is not closed with '---'")

    description = None
    paths = None
    current_list = None
    for number, line in enumerate(lines[1:end], start=2):
        if not line.strip():
            continue
        if line.startswith(("  - ", "- ")) and current_list is not None:
            item = unquote(line.split("- ", 1)[1])
            if not item:
                fail(f"{path.relative_to(root)}:{number}: empty path entry")
            current_list.append(item)
            continue
        match = re.match(r"^([a-z_]+):\s*(.*)$", line)
        if not match:
            fail(f"{path.relative_to(root)}:{number}: cannot parse frontmatter line: {line!r}")
        key, value = match.group(1), match.group(2)
        if key == "description":
            description = unquote(value)
            current_list = None
        elif key == "paths":
            if value.strip() not in ("", "[]"):
                fail(f"{path.relative_to(root)}:{number}: write paths as a YAML list, one '  - \"glob\"' per line")
            paths = []
            current_list = paths
        else:
            fail(f"{path.relative_to(root)}:{number}: unknown frontmatter key '{key}' (allowed: description, paths)")

    if not description:
        fail(f"{path.relative_to(root)}: 'description' is required")
    body = "\n".join(lines[end + 1:]).strip("\n") + "\n"
    if not body.strip():
        fail(f"{path.relative_to(root)}: rule body is empty")
    return {"description": description, "paths": paths or [], "body": body}


def yaml_quote(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def claude_content(name: str, rule: dict) -> str:
    header = ""
    if rule["paths"]:
        header = "---\npaths:\n" + "".join(f"  - {yaml_quote(p)}\n" for p in rule["paths"]) + "---\n"
    return f"{header}{marker(name)}\n\n{rule['body']}"


def cursor_content(name: str, rule: dict) -> str:
    always = not rule["paths"]
    lines = ["---", f"description: {rule['description']}"]
    if always:
        lines.append("alwaysApply: true")
    else:
        lines.append(f"globs: {', '.join(rule['paths'])}")
        lines.append("alwaysApply: false")
    lines.append("---")
    return "\n".join(lines) + f"\n{marker(name)}\n\n{rule['body']}"


def routing_table(rules: dict) -> str:
    rows = [
        "| Rule | Applies to | Read |",
        "|---|---|---|",
    ]
    ordered = sorted(rules.items(), key=lambda item: (bool(item[1]["paths"]), item[0]))
    for name, rule in ordered:
        applies = "always" if not rule["paths"] else ", ".join(f"`{p}`" for p in rule["paths"])
        rows.append(f"| {name}: {rule['description']} | {applies} | `.claude/rules/{name}.md` |")
    return "\n".join(rows)


def is_generated(path: Path) -> bool:
    try:
        head = path.read_text(encoding="utf-8").split("\n")[:12]
    except (OSError, UnicodeDecodeError):
        return False
    return any(line.startswith(MARKER_PREFIX) for line in head)


# ---------------------------------------------------------------- sources
rules: dict = {}
for path in sorted(source_dir.glob("*.md")):
    if path.name == "README.md":
        continue
    name = path.stem
    if not NAME_PATTERN.match(name):
        fail(f"{path.relative_to(root)}: rule names must be kebab-case (a-z, 0-9, '-')")
    rules[name] = parse_source(path)

if not rules:
    fail("No rules found in .agents/rules/")

# ---------------------------------------------------------------- expected outputs
expected: dict = {}
for name, rule in rules.items():
    expected[claude_dir / f"{name}.md"] = claude_content(name, rule)
    expected[cursor_dir / f"{name}.mdc"] = cursor_content(name, rule)

if not claude_md.exists():
    fail("CLAUDE.md not found")
claude_text = claude_md.read_text(encoding="utf-8")
if claude_text.count(BEGIN_TABLE) != 1 or claude_text.count(END_TABLE) != 1:
    fail(f"CLAUDE.md must contain exactly one '{BEGIN_TABLE}' and one '{END_TABLE}' marker")
before, rest = claude_text.split(BEGIN_TABLE)
_, after = rest.split(END_TABLE)
new_claude_text = f"{before}{BEGIN_TABLE}\n{routing_table(rules)}\n{END_TABLE}{after}"

# ---------------------------------------------------------------- compare / write
drift = False
for target_dir, suffix in ((claude_dir, ".md"), (cursor_dir, ".mdc")):
    existing = sorted(target_dir.glob(f"*{suffix}")) if target_dir.exists() else []
    for path in existing:
        if path in expected:
            continue
        relative = path.relative_to(root)
        if is_generated(path):
            if check_only:
                print(f"Orphaned (source removed): {relative}")
                drift = True
            else:
                path.unlink()
                print(f"Removed orphan: {relative}")
        elif check_only:
            print(f"Unmanaged (left untouched): {relative}")

for path, content in sorted(expected.items()):
    relative = path.relative_to(root)
    current = path.read_text(encoding="utf-8") if path.exists() else None
    if current == content:
        continue
    if check_only:
        print(f"{'Missing' if current is None else 'Out of sync'}: {relative}")
        drift = True
    else:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
        print(f"Generated: {relative}")

if new_claude_text != claude_text:
    if check_only:
        print("Out of sync: CLAUDE.md (agent rules table)")
        drift = True
    else:
        claude_md.write_text(new_claude_text, encoding="utf-8")
        print("Updated: CLAUDE.md (agent rules table)")

if check_only:
    if drift:
        print("Agent rules are out of sync. Run: bash ./scripts/sync_agent_rules.sh", file=sys.stderr)
        sys.exit(1)
    print("All agent rules in sync.")
PYTHON
